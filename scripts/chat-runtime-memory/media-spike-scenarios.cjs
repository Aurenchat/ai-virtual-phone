const assert = require('node:assert/strict');
module.exports = async function scenarios({ page, check, waitForRequest, resolveReply }) {
    const read = () => page.evaluate(() => window.mediaSpikeTest.stats());
    const leave = async () => {
        await page.evaluate(() => window.mediaSpikeTest.leave());
        await page.waitForFunction(() => !document.getElementById('app').children.length);
    };
    await page.evaluate(() => { window.mediaSpikeTest.setupPanel(); window.mediaSpikeTest.panel(); });
    const grid = page.locator('.grid.grid-cols-5');
    await grid.waitFor();
    await page.waitForFunction(() => window.mediaSpikeTest.stats().active === 2);
    let stats = await read();
    check(stats.calls.length === 2 && stats.calls.every(id => id.startsWith('panel-asset-0-')), 'five packs / 100 stickers: only active pack starts near-visible reads');
    check(stats.calls.filter(id => id === 'panel-asset-0-0').length === 1, 'same asset in two visible panel tiles shares one read');
    check(await grid.locator('img[alt="panel-0-2"]').getAttribute('src') === await page.evaluate(() => window.mediaSpikeTest.PNG), 'external panel sticker displays directly without asset read');
    check(!stats.calls.includes('panel-asset-0-2'), 'external URL does not enter IndexedDB resolver');
    await page.getByRole('button', { name: 'Panel pack 1', exact: true }).click();
    await page.evaluate(() => window.mediaSpikeTest.releasePanel());
    await page.waitForFunction(() => window.mediaSpikeTest.stats().active === 0 && window.mediaSpikeTest.stats().calls.some(id => id.startsWith('panel-asset-1-')));
    stats = await read();
    check(stats.calls.filter(id => id.startsWith('panel-asset-0-')).length === 2 && stats.calls.some(id => id.startsWith('panel-asset-1-')), 'switch pack skips queued old-pack reads and resolves new active pack');
    check(stats.peak <= 2, 'panel resolve concurrency never exceeds two');
    check(stats.calls.every(id => !/^panel-asset-[234]-/.test(id)), 'inactive packs perform zero local image reads');
    await leave();
    await page.evaluate(() => { window.mediaSpikeTest.extendPanel(); window.mediaSpikeTest.resetPanel(); window.mediaSpikeTest.panel(); window.mediaSpikeTest.releasePanel(); });
    await grid.waitFor();
    await page.waitForFunction(() => window.mediaSpikeTest.stats().calls.length > 2 && window.mediaSpikeTest.stats().active === 0);
    stats = await read();
    check(stats.calls.length < 59 && !stats.calls.includes('panel-asset-0-59'), 'offscreen active-pack tiles are not read until near viewport');
    await grid.evaluate(el => { el.scrollTop = el.scrollHeight; });
    await page.waitForFunction(() => window.mediaSpikeTest.stats().calls.includes('panel-asset-0-59') && window.mediaSpikeTest.stats().active === 0);
    check((await read()).calls.length > stats.calls.length, 'scrolling resolves newly near-visible tiles');
    const scrollBefore = await grid.evaluate(el => el.scrollTop);
    const diagBefore = await page.evaluate(() => window.__diagWrites.length);
    await page.evaluate(() => window.mediaSpikeTest.panel());
    await page.waitForTimeout(50);
    check(await grid.evaluate(el => el.scrollTop) === scrollBefore && await page.evaluate(n => window.__diagWrites.length === n, diagBefore), 'equivalent participant-array rerender preserves panel scroll and does not write per-tile breadcrumbs');
    await leave();
    await page.evaluate(() => { window.mediaSpikeTest.resetPanel(); window.mediaSpikeTest.panel(); });
    await page.waitForFunction(() => window.mediaSpikeTest.stats().active === 2);
    const updates = await page.evaluate(() => window.__panelTileUpdates || 0);
    await leave(); await page.evaluate(() => window.mediaSpikeTest.releasePanel());
    await page.waitForFunction(() => window.mediaSpikeTest.stats().active === 0);
    check(await page.evaluate(n => (window.__panelTileUpdates || 0) === n, updates), 'pending panel reads never set tile state after unmount');
    check((await read()).calls.length === 2, 'panel unmount drops queued reads while allowing active reads to settle');
    const caches = await page.evaluate(() => window.mediaSpikeTest.cacheTests());
    check(caches.entries.keys.length === 24 && caches.entries.keys.includes('0') && !caches.entries.keys.includes('1'), 'panel LRU caps 24 entries and retains touched asset');
    check(caches.chars.chars <= 6 * 1024 * 1024 && caches.chars.keys.length <= 24 && !caches.chars.keys.includes('large-0'), 'panel cache also evicts oldest entries for character budget');
    check(caches.oversize === undefined && caches.disposed.keys.length === 0 && caches.disposed.chars === 0, 'oversized values bypass LRU and disposal releases cache');
    await page.evaluate(() => window.mediaSpikeTest.oversizeTile());
    await page.waitForFunction(() => document.querySelector('img[alt="huge"]')?.naturalWidth > 0);
    check(true, 'single sticker larger than cache budget still displays');
    const huge = await page.evaluate(() => window.mediaSpikeTest.oversizeCache());
    check(huge.length > 6 * 1024 * 1024 && huge.cached === undefined && huge.snapshot.chars === 0, 'oversized resolver result reaches caller without entering panel cache');
    await leave();

    await page.evaluate(() => window.mediaSpikeTest.setupPhoto());
    await page.locator('.chat-room-wrapper').waitFor();
    const openPhoto = async () => {
        await page.locator('button:has(svg line[x1="12"][y1="8"])').click();
        await page.getByText('照片墙', { exact: true }).click();
        await page.getByText('发送照片', { exact: true }).waitFor();
    };
    const image = Buffer.from((await page.evaluate(() => window.mediaSpikeTest.PNG)).split(',')[1], 'base64');
    const pick = name => page.locator('.modal-dialog input[type=file]').setInputFiles({ name, mimeType: 'image/png', buffer: image });
    await openPhoto(); await pick('one.png');
    const preview = page.locator('img[alt=preview]');
    await page.waitForFunction(() => document.querySelector('img[alt=preview]')?.src.startsWith('blob:'));
    const first = await preview.getAttribute('src');
    await pick('two.png'); await page.waitForFunction(old => document.querySelector('img[alt=preview]')?.src !== old, first);
    const second = await preview.getAttribute('src');
    check(await page.evaluate(url => window.__urls.revoked.includes(url), first), 'replacing uploaded file revokes previous preview object URL');
    check(await page.evaluate(() => window.mediaSpikeTest.photoStats().reads === 0), 'photo selection never calls FileReader.readAsDataURL');
    await page.locator('.modal-dialog').getByRole('button', { name: '取消', exact: true }).click();
    check(await page.evaluate(url => window.__urls.revoked.includes(url), second), 'photo modal unmount revokes preview URL');
    await openPhoto(); await pick('persist.png');
    const before = await page.evaluate(() => window.mediaSpikeTest.messages().length);
    await page.locator('.modal-dialog').getByRole('button', { name: '发送', exact: true }).click();
    await page.waitForFunction(() => window.mediaSpikeTest.photoStats().stores === 1);
    check(await page.locator('.modal-dialog').getByRole('button', { name: '发送', exact: true }).isDisabled(), 'photo send disabled during pending Blob store');
    check(await page.evaluate(() => window.mediaSpikeTest.runtime().current.stage === 'PHOTO_STORE_BEGIN'), 'pending photo write retains PHOTO_STORE_BEGIN crash evidence');
    await page.locator('.modal-dialog').getByRole('button', { name: '发送', exact: true }).evaluate(el => { el.click(); el.click(); });
    await page.evaluate(() => window.mediaSpikeTest.releasePhoto());
    await page.waitForFunction(n => window.mediaSpikeTest.messages().length === n + 1, before);
    await page.waitForFunction(() => !document.querySelector('img[alt=preview]'));
    const saved = await page.evaluate(() => window.mediaSpikeTest.storedPhoto());
    check(saved.msg.mediaUrl.startsWith('media-store://') && saved.bytes === image.length && saved.mime === 'image/png', 'new photo message persists a media-store reference and original Blob');
    check(await page.evaluate(() => { const r = window.mediaSpikeTest.runtime().current; return r.stage === 'PHOTO_DONE' && r.completed && window.mediaSpikeTest.photoStats().stores === 1; }), 'single Blob write completes photo diagnostics without duplicate send');
    await leave(); await page.evaluate(() => window.mediaSpikeTest.room());
    await page.waitForFunction(() => [...document.querySelectorAll('.chat-room-wrapper img')].some(img => img.src.startsWith('blob:') && img.naturalWidth > 0));
    check(true, 'fresh room resolves persisted uploaded photo from media store');
    await openPhoto(); await pick('failure.png');
    const failureBefore = await page.evaluate(() => window.mediaSpikeTest.messages().length);
    await page.locator('.modal-dialog').getByRole('button', { name: '发送', exact: true }).click();
    await page.waitForFunction(() => window.mediaSpikeTest.photoStats().stores === 2);
    await page.evaluate(() => window.mediaSpikeTest.releasePhoto(true));
    await page.waitForFunction(() => !document.querySelector('.modal-dialog button.ui-btn-success').disabled);
    check(await page.evaluate(n => window.mediaSpikeTest.messages().length === n, failureBefore), 'failed media store does not push a partial image message');
    await page.evaluate(() => {
        window.__workingDiagSet = Storage.prototype.setItem;
        Storage.prototype.setItem = function(k, v) {
            if (k.includes('_diag_')) throw new DOMException('Intentional diagnostic quota', 'QuotaExceededError');
            return window.__workingDiagSet.call(this, k, v);
        };
    });
    await page.locator('.modal-dialog').getByRole('button', { name: '发送', exact: true }).click();
    await page.waitForFunction(() => window.mediaSpikeTest.photoStats().stores === 3);
    await page.evaluate(() => window.mediaSpikeTest.releasePhoto(false));
    await page.waitForFunction(n => window.mediaSpikeTest.messages().length === n + 1 && !document.querySelector('img[alt=preview]'), failureBefore);
    check(true, 'real photo save and send succeed when diagnostic localStorage writes throw');
    await page.evaluate(() => { Storage.prototype.setItem = window.__workingDiagSet; });
    await page.evaluate(() => window.mediaSpikeTest.legacyPhoto());
    await page.waitForFunction(() => [...document.querySelectorAll('.chat-room-wrapper img')].some(img => img.src.startsWith('data:image/') && img.naturalWidth > 0));
    check(true, 'legacy data URL photos still render');
    await leave();

    await page.evaluate(() => { window.mediaSpikeTest.holdFrames(); window.mediaSpikeTest.call('character', true, true); });
    await page.locator('.ui-call-btn-success').waitFor();
    let call = await page.evaluate(() => window.mediaSpikeTest.callStats());
    check(call.history.every(n => n === 1) && !call.audio.includes(true), 'strict-mode incoming mount only checks last record and never activates audio');
    check(call.bgReads === 0 && await page.locator('.ui-call-btn-success').isVisible(), 'first incoming screen commits before background read');
    const initialCallRecords = await page.evaluate(() => window.hostMemoryTest.messages().filter(m => m.content.includes('发起了语音通话')).length);
    check(initialCallRecords === 1, 'StrictMode effect replay does not duplicate initiation record');
    await page.evaluate(() => window.mediaSpikeTest.flushFrame());
    check((await page.evaluate(() => window.mediaSpikeTest.callStats())).bgReads === 0, 'first animation frame still does not decode call background');
    await page.evaluate(() => window.mediaSpikeTest.flushFrame());
    await page.waitForFunction(() => window.mediaSpikeTest.callStats().bgReads === 1);
    await page.locator('.ui-call-btn-danger').click();
    await page.waitForFunction(() => !document.querySelector('.ui-call-btn-success'));
    const bgUpdates = await page.evaluate(() => window.__callBgUpdates || 0);
    await page.evaluate(() => { window.mediaSpikeTest.releaseBackground(); window.mediaSpikeTest.restoreFrames(); });
    await page.waitForTimeout(50);
    check(await page.evaluate(n => (window.__callBgUpdates || 0) === n, bgUpdates), 'late background resolve never updates unmounted incoming screen');
    call = await page.evaluate(() => window.mediaSpikeTest.callStats());
    check(!call.history.includes('full') && !call.audio.includes(true), 'reject before accept never loads full history or activates call audio');
    check(await page.evaluate(() => window.mediaSpikeTest.runtime().current.completed), 'decline marks call ended without waiting for background');

    await page.evaluate(() => window.mediaSpikeTest.call('character', true));
    await page.locator('.ui-call-btn-success').waitFor();
    await page.waitForFunction(() => window.mediaSpikeTest.callStats().bgReads === 1);
    await page.evaluate(() => window.mediaSpikeTest.releaseBackground());
    await page.waitForFunction(() => document.querySelector('.call-bg-default')?.style.background.includes('data:image/png'));
    check(true, 'deferred call background restores the existing final visual');
    await page.locator('.ui-call-btn-success').click();
    await page.waitForFunction(() => window.mediaSpikeTest.callStats().audio.includes(true));
    call = await page.evaluate(() => window.mediaSpikeTest.callStats());
    check(call.history.filter(n => n === 'full').length === 1, 'accept loads full call history exactly once');
    await page.getByPlaceholder('输入你想说的话...').fill('Call context fixture');
    await page.getByPlaceholder('输入你想说的话...').press('Enter');
    await waitForRequest();
    call = await page.evaluate(() => window.mediaSpikeTest.callStats());
    check(call.contexts[0].some(m => m.content === 'history-0') && call.contexts[0].some(m => m.content.includes('发起了语音通话')), 'first AI call turn retains full old history plus persisted initiation message');
    resolveReply('Call response fixture');
    await page.getByPlaceholder('输入你想说的话...').waitFor();
    check((await page.evaluate(() => window.mediaSpikeTest.callStats())).audio.filter(x => x === true).length === 1, 'processing and speech state changes do not rebuild audio session');
    await page.locator('.ui-call-btn-danger').click();
    await page.waitForFunction(() => !document.getElementById('app').children.length);
    check(!(await page.evaluate(() => window.mediaSpikeTest.callStats())).audio.at(-1), 'hangup/unmount releases audio session');
    await page.evaluate(() => window.mediaSpikeTest.call('user', false));
    await page.locator('.ui-call-btn-danger').waitFor();
    await page.waitForTimeout(1200);
    check(!(await page.evaluate(() => window.mediaSpikeTest.callStats())).history.includes('full'), 'user call retains dialing delay and defers full history');
    await page.waitForFunction(() => window.mediaSpikeTest.callStats().audio.includes(true), null, { timeout: 6000 });
    check((await page.evaluate(() => window.mediaSpikeTest.callStats())).history.filter(n => n === 'full').length === 1, 'user auto-connect loads full history once after three-second dial');
    await leave();
    await page.evaluate(() => window.mediaSpikeTest.groupGeneration());
    await page.locator('.chat-room-wrapper').waitFor();
    await page.evaluate(() => window.mediaSpikeTest.triggerGroup());
    await waitForRequest();
    check(await page.evaluate(() => { const r = window.mediaSpikeTest.generation().current; return r.isGroup && r.lastStage === 'PROVIDER_REQUEST_BEGIN' && r.providerRequestStarted === true && !r.completed; }), 'group generation records pending API diagnostics');
    resolveReply('[Memory A]: Group diagnostic reply one\n\nGroup diagnostic reply two');
    await page.waitForFunction(() => window.mediaSpikeTest.generation().current?.completed);
    const group = await page.evaluate(() => window.mediaSpikeTest.generation().current);
    check(group.isGroup && group.publishedCount === 2 && group.draftCount === 2 && group.rawLength > 0 && group.lastStage === 'GEN_FINALLY', 'group response, parse, staged publishing and finally share accurate diagnostic counters');
    await leave();
    await page.evaluate(() => window.mediaSpikeTest.diagnostics());
    await page.getByText('聊天运行诊断（仅本机）', { exact: true }).click();
    check(await page.getByRole('button', { name: '刷新诊断', exact: true }).isVisible(), 'settings diagnostics exposes manual refresh');
    check(await page.getByText(/不包含聊天正文、提示词、图片内容或 API 密钥/).isVisible(), 'diagnostics UI explains privacy and incomplete-record ambiguity');
    check(await page.getByText('publishedCount：', { exact: true }).count() > 0 && await page.getByText('initiator：', { exact: true }).count() > 0, 'diagnostics UI renders generation counters and runtime metadata');
    const sensitive = await page.evaluate(() => window.__diagWrites.some(w => /history-0|Call context fixture|Paced reply|data:image|fixture-only/.test(JSON.stringify(w.record))));
    assert.equal(sensitive, false); check(true, 'all real diagnostic records omit message bodies, image data and API credentials');
    await leave();
};
